# KlarCam filter host for OBS Studio: a small libobs SDK (headers + import
# library) matching the OBS Studio installed on this machine, for building the
# host on its own. No libobs build, no obs-deps.
#
# SPDX-License-Identifier: GPL-2.0-or-later
# Copyright (C) 2026 Lars von Thienen
#
#  1. Reads the installed OBS version from obs64.exe.
#  2. Fetches the matching obs-studio tag's libobs and w32-pthreads headers (a
#     sparse git clone of https://github.com/obsproject/obs-studio).
#  3. Makes obs.lib from the export table of the installed obs.dll (dumpbin, lib).
#  4. Writes obsconfig.h.
# Result: <host folder>\.deps\libobs-sdk\{include,lib}, where CMakeLists.txt looks.
param(
  [string]$ObsDir = "C:\Program Files\obs-studio",
  [string]$Tag = "",
  [string]$OutDir = (Join-Path (Split-Path $PSScriptRoot -Parent) ".deps\libobs-sdk")
)
$ErrorActionPreference = "Stop"

$obsExe = Join-Path $ObsDir "bin\64bit\obs64.exe"
$obsDll = Join-Path $ObsDir "bin\64bit\obs.dll"
if (-not (Test-Path $obsDll)) { throw "obs.dll not found under $ObsDir" }

if (-not $Tag) {
  $v = (Get-Item $obsExe).VersionInfo
  $Tag = "$($v.FileMajorPart).$($v.FileMinorPart).$($v.FileBuildPart)"
}
Write-Host "OBS version / tag: $Tag"

New-Item -ItemType Directory -Force (Join-Path $OutDir "include") | Out-Null
New-Item -ItemType Directory -Force (Join-Path $OutDir "lib") | Out-Null

# --- 1. headers ------------------------------------------------------------
$src = Join-Path $OutDir "obs-studio-src"
if (-not (Test-Path (Join-Path $src "libobs\obs.h"))) {
  if (Test-Path $src) { Remove-Item -Recurse -Force $src }
  git clone --quiet --depth 1 --filter=blob:none --sparse --branch $Tag https://github.com/obsproject/obs-studio $src
  if (-not $?) { throw "git clone failed" }
  git -C $src sparse-checkout set libobs deps/w32-pthreads
  if (-not $?) { throw "sparse-checkout failed" }
}

$inc = Join-Path $OutDir "include"
$libobsDir = Join-Path $src "libobs"
Get-ChildItem -Path $libobsDir -Recurse -Include *.h,*.hpp | ForEach-Object {
  $rel = $_.FullName.Substring($libobsDir.Length + 1)
  $dest = Join-Path $inc $rel
  New-Item -ItemType Directory -Force (Split-Path $dest -Parent) | Out-Null
  Copy-Item $_.FullName $dest -Force
}
$pth = Join-Path $inc "w32-pthreads"
New-Item -ItemType Directory -Force $pth | Out-Null
foreach ($h in "pthread.h", "sched.h", "semaphore.h") {
  Copy-Item (Join-Path $src "deps\w32-pthreads\$h") (Join-Path $pth $h) -Force
}

# obsconfig.h (normally generated by the obs-studio CMake configure)
$obsconfig = @"
#pragma once
/* Generated by tools/make-libobs-sdk.ps1 for OBS $Tag */
#define OBS_VERSION "$Tag"
#define OBS_VERSION_CANONICAL "$Tag"
#define OBS_INSTALL_PREFIX ""
#define OBS_DATA_PATH "../../data"
#define OBS_PLUGIN_PATH "../../obs-plugins/64bit"
#define OBS_PLUGIN_DESTINATION "obs-plugins/64bit"
#define OBS_RELEASE_CANDIDATE 0
#define OBS_BETA 0
"@
$obsconfig | Out-File -Encoding ascii (Join-Path $inc "obsconfig.h")

# --- 2. import library -----------------------------------------------------
$vswhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
$vsPath = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
if (-not $vsPath) { throw "No Visual Studio with C++ tools found" }
$msvcVer = (Get-Content (Join-Path $vsPath "VC\Auxiliary\Build\Microsoft.VCToolsVersion.default.txt")).Trim()
$bin = Join-Path $vsPath "VC\Tools\MSVC\$msvcVer\bin\Hostx64\x64"
Write-Host "MSVC tools: $bin"

$exports = & (Join-Path $bin "dumpbin.exe") /NOLOGO /EXPORTS $obsDll
$names = New-Object System.Collections.Generic.List[string]
foreach ($line in $exports) {
  if ($line -match '^\s+\d+\s+[0-9A-Fa-f]+\s+[0-9A-Fa-f]{8}\s+(\S+)') { $names.Add($Matches[1]) }
}
if ($names.Count -lt 100) { throw "Unexpected export count $($names.Count) from obs.dll" }
Write-Host "obs.dll exports: $($names.Count)"

$def = Join-Path $OutDir "lib\obs.def"
$content = @("LIBRARY obs.dll", "EXPORTS") + $names
[System.IO.File]::WriteAllLines($def, $content, (New-Object System.Text.ASCIIEncoding))
$outLib = Join-Path $OutDir "lib\obs.lib"
& (Join-Path $bin "lib.exe") /NOLOGO "/DEF:$def" /MACHINE:X64 "/OUT:$outLib"
if (-not $?) { throw "lib.exe failed" }

Write-Host "libobs SDK ready in $OutDir"
